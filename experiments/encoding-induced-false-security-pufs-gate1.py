def bits_to_bytes(C):
    N = C.shape[0]
    B = np.zeros((N, 8), dtype=np.uint8)
    for i in range(8):
        chunk = C[:, 8*i:8*i+8]
        B[:, i] = np.packbits(chunk, axis=1).ravel()
    return B

def bytes_to_bits(B):
    N = B.shape[0]
    C = np.zeros((N, 64), dtype=np.uint8)
    for i in range(8):
        C[:, 8*i:8*i+8] = np.unpackbits(B[:, i:i+1], axis=1)
    return C

def pi_sbox(C): return bytes_to_bits(SBOX_ARR[bits_to_bytes(C)])
def pi_inv(C): return bytes_to_bits(INV_ARR[bits_to_bytes(C)])

def parity_feats(C):
    S = 1 - 2*C.astype(np.float64)
    X = np.ones((C.shape[0], 65))
    for i in range(64):
        X[:, i] = np.prod(S[:, i:], axis=1)
    return X

def to_pm(C01):
    """Bits {0,1} -> pypuf challenge convention {-1,+1}. All puf.eval calls use this."""
    return (2*C01.astype(np.int8) - 1)

def labels(puf, C01):
    C01 = np.asarray(C01)
    assert set(np.unique(C01)) <= {0, 1}, 'labels() expects {0,1} challenges (did you double-apply to_pm?)'
    return ((puf.eval(to_pm(C01)).reshape(-1) + 1)//2).astype(int)

def run_lr(Xtr, ytr, Xte, yte, seed):
    if len(np.unique(ytr)) < 2:  # degenerate instance: constant predictor
        maj = np.bincount(yte).argmax()
        return float((yte == maj).mean())
    clf = LogisticRegression(max_iter=1000, C=1.0, solver='liblinear', random_state=seed)
    clf.fit(Xtr, ytr)
    return float(clf.score(Xte, yte))

